/**
 * Compile only the reviewed opening projection of moon-z-life.
 * Do not bundle the full skill: its other sections describe unexperienced facts.
 * Markdown remains the source of truth; no credential or network access here.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const DEFAULT_ROOT = fileURLToPath(new URL('../', import.meta.url));
const SKILL_DIRECTORY = 'skills/moon-z-life';
const SOURCE_FILES = Object.freeze([
  'SKILL.md', 'references/z-profile.md', 'references/z-voice.md',
  'references/world.md', 'references/plot.md',
]);
const digest = value => createHash('sha256').update(value, 'utf8').digest('hex');
const clean = value => value.replace(/\r\n?/g, '\n').trim();

function section(markdown, heading) {
  const lines = markdown.replace(/\r\n?/g, '\n').split('\n');
  const indexes = lines.flatMap((line, index) => line === `## ${heading}` ? [index] : []);
  if (indexes.length !== 1) throw new Error(`moon-z-life: expected one reviewed section: ${heading}`);
  const start = indexes[0] + 1;
  let end = start;
  while (end < lines.length && !/^#{1,2} /.test(lines[end])) end++;
  const text = clean(lines.slice(start, end).join('\n'));
  if (!text) throw new Error(`moon-z-life: empty reviewed section: ${heading}`);
  return text;
}
function paragraph(markdown, heading) {
  return section(markdown, heading).split(/\n\s*\n/)[0];
}
function tableRow(markdown, heading, label) {
  const rows = section(markdown, heading).split('\n').filter(line => line.startsWith(`| ${label} |`));
  if (rows.length !== 1 || !rows[0].endsWith('|')) throw new Error(`moon-z-life: missing reviewed opening row: ${label}`);
  return rows[0].slice(`| ${label} |`.length, -1).trim();
}

/** No caller-provided day, scene or history can alter this release's setting. */
const CURRENT_WORLD = Object.freeze({ day: 'opening', time: 'night', scene: 'live_room' });

export async function compileZSkill(root = DEFAULT_ROOT) {
  const files = await Promise.all(SOURCE_FILES.map(async file => {
    const raw = await fs.readFile(path.join(root, SKILL_DIRECTORY, file), 'utf8');
    return { file, raw, sha256: digest(raw) };
  }));
  const byFile = Object.fromEntries(files.map(item => [item.file, item.raw]));
  const excerpts = [
    { file: 'SKILL.md', section: '你是谁 / 首段', text: paragraph(byFile['SKILL.md'], '你是谁') },
    { file: 'SKILL.md', section: '人设速查（细节见 z-profile.md）', text: section(byFile['SKILL.md'], '人设速查（细节见 z-profile.md）') },
    { file: 'references/z-profile.md', section: '核心', text: section(byFile['references/z-profile.md'], '核心') },
    { file: 'references/z-profile.md', section: '核心矛盾与触发', text: section(byFile['references/z-profile.md'], '核心矛盾与触发') },
    { file: 'references/z-voice.md', section: '全文 / 仅作语言风格参考', text: clean(byFile['references/z-voice.md']) },
    { file: 'references/world.md', section: '第1层 小岛世界（Z 的认知层）', text: section(byFile['references/world.md'], '第1层 小岛世界（Z 的认知层）') },
    { file: 'references/plot.md', section: 'opening · 直播初见 / 怎么反应', text: tableRow(byFile['references/plot.md'], 'opening · 直播初见', '怎么反应') },
  ];
  // Fail closed if reviewed headings are later expanded into protected material.
  // This is a backstop, not a replacement for reviewing the explicit selections.
  const protectedContent = /day_[1-7]|Day\s*[1-7]|公司制造|新一代\s*AI|替代计划|撤销|毁灭|行动点|任务链|剧情标志|NPC|z_state_update|suspicion_level|第[02]层|结局台词/iu;
  for (const excerpt of excerpts) {
    if (protectedContent.test(excerpt.text)) throw new Error(`moon-z-life: protected content in reviewed excerpt: ${excerpt.file} / ${excerpt.section}`);
  }
  const prompt = excerpts.map((item, index) => `【角色素材 ${index + 1}】\n${item.text}`).join('\n\n');
  const meta = {
    id: 'moon-z-life', version: 1, projection: 'opening-live-room',
    world: { ...CURRENT_WORLD }, projectionSha256: digest(prompt),
    sources: files.map(({ file, sha256 }) => ({ file: `${SKILL_DIRECTORY}/${file}`, sha256,
      selections: excerpts.filter(item => item.file === file).map(item => ({ section: item.section, sha256: digest(item.text) })) })),
  };
  return { prompt, meta, world: { ...CURRENT_WORLD } };
}

export function renderZPersona({ prompt, meta, world }) {
  return `// Generated by scripts/z-skill.mjs from the reviewed opening Markdown projection.\n// Run npm run build after editing the skill. Do not add unexperienced story material.\nexport const Z_PERSONA = ${JSON.stringify(prompt)};\nexport const Z_PERSONA_META = Object.freeze(${JSON.stringify(meta, null, 2)});\nexport const Z_CURRENT_WORLD = Object.freeze(${JSON.stringify(world)});\n`;
}

export async function writeZPersona(root = DEFAULT_ROOT) {
  const compiled = await compileZSkill(root);
  await fs.writeFile(path.join(root, 'worker/z-persona.js'), renderZPersona(compiled));
  return compiled;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { meta } = await writeZPersona();
  console.log(`Compiled ${meta.id} opening projection from ${meta.sources.length} Markdown files (${meta.projectionSha256.slice(0, 12)}).`);
}
